CREATE TABLE intranet_param (
    id integer NOT NULL DEFAULT 1,
    ldap_host character varying(40) NOT NULL DEFAULT 'ldap.example.com'::character varying,
    ldap_port character varying(30) NOT NULL DEFAULT '389'::character varying,
    ldap_domain character varying(40) NOT NULL DEFAULT '@example.com'::character varying,
    ldap_base character varying(50) NOT NULL DEFAULT 'dc=example,dc=com'::character varying,
    email_sender_user character varying(30) NOT NULL DEFAULT 'sender@example.com'::character varying,
    email_sender_pass character varying(64) NOT NULL DEFAULT ''::character varying,
    email_receiver character varying(500) NOT NULL DEFAULT 'receiver@example.com'::character varying,
    email_smtp_host character varying(40) NOT NULL DEFAULT 'smtp.example.com'::character varying,
    email_smtp_port character varying(40) NOT NULL DEFAULT '587'::character varying,
    email_name character varying(40) NOT NULL DEFAULT 'CyberSculpt - Intranet'::character varying,
    email_subject character varying(150) NOT NULL DEFAULT 'CyberSculpt - Intranet, Nova maquina Requisitada.'::character varying,
    email_attachment_name character varying(40) NOT NULL DEFAULT 'Formulario'::character varying,
    message_title character varying(150) NOT NULL DEFAULT 'CyberSculpt - Intranet, atualizacao de status em seu pedido de novo utilizador.'::character varying,
    email_cc character varying(500),
    message_cc character varying(500),
    activate_receiver_feedback boolean NOT NULL DEFAULT false,
    activate_return_postform boolean NOT NULL DEFAULT false,
    settings_user character varying(40) NOT NULL DEFAULT 'CHANGE_ME_USER'::character varying,
    settings_pass character varying(40) NOT NULL DEFAULT 'CHANGE_ME_PASSWORD'::character varying,
    email_smtp_encryption character varying(10) NOT NULL DEFAULT 'tls'::character varying,
    secretkey character varying(16) NOT NULL DEFAULT 'CHANGE_ME_KEY'::character varying,
    activate_prebuilt_message boolean NOT NULL DEFAULT true,
    PRIMARY KEY (id)
);

CREATE TABLE form_values (
    id_pedido integer NOT NULL DEFAULT nextval('form_values_id_pedido_seq'::regclass),
    act_empresa character varying(40),
    comp_nome character varying(40),
    alt_nome character varying(40),
    act_departamento character varying(40),
    superior character varying(40),
    pc_note character varying(200),
    penkanguru boolean,
    cr_email boolean,
    sug_email character varying(40),
    type_mail character varying(40),
    type_tele character varying(40),
    card_tele boolean,
    dados_tele character varying(40),
    cr_sap boolean,
    easy_schedule boolean,
    cpis_user character varying(40),
    server_user character varying(40),
    vpn boolean,
    office_lang character varying(40),
    alt_office_lang character varying(40),
    services character varying(40),
    alt_services character varying(40),
    cyber_card boolean,
    cyber_profile character varying(40),
    obs character varying(200),
    data_pedido timestamp without time zone,
    status_pedido character varying(40),
    contact_email character varying(40),
    contact_nome character varying(40),
    last_update timestamp without time zone,
    PRIMARY KEY (id_pedido)
);

CREATE TABLE computador (
    pc_id integer NOT NULL DEFAULT nextval('computador_pc_id_seq'::regclass),
    pedido_id integer NOT NULL,
    pc_name character varying,
    pc_mac character varying(40),
    pc_so character varying(40),
    pc_cpu character varying(40),
    pc_mem character varying(40),
    pc_drive character varying(40),
    pc_serial character varying(40),
    admin_user character varying(40),
    admin_pass character varying(64),
    pc_malfunctions character varying(200),
    username character varying(40),
    user_pass character varying(64),
    PRIMARY KEY (pc_id)
);

CREATE TABLE checklist (
    check_id integer NOT NULL DEFAULT nextval('checklist_check_id_seq'::regclass),
    id_maquina integer NOT NULL,
    list_fields character varying(600),
    PRIMARY KEY (check_id)
);


CREATE TABLE users (
    id integer NOT NULL DEFAULT nextval('users_id_seq'::regclass),
    username text,
    block boolean,
    lang text,
    PRIMARY KEY (id)
);

CREATE VIEW maquinasview AS  SELECT form_values.id_pedido,
    form_values.act_empresa,
    form_values.comp_nome,
    form_values.alt_nome,
    form_values.act_departamento,
    form_values.superior,
    form_values.pc_note,
    form_values.penkanguru,
    form_values.cr_email,
    form_values.sug_email,
    form_values.type_mail,
    form_values.type_tele,
    form_values.card_tele,
    form_values.dados_tele,
    form_values.cr_sap,
    form_values.easy_schedule,
    form_values.cpis_user,
    form_values.server_user,
    form_values.vpn,
    form_values.office_lang,
    form_values.alt_office_lang,
    form_values.services,
    form_values.alt_services,
    form_values.cyber_card,
    form_values.cyber_profile,
    form_values.obs,
    form_values.data_pedido,
    form_values.status_pedido,
    form_values.contact_email,
    form_values.contact_nome,
    form_values.last_update,
    computador.pc_id,
    computador.pedido_id,
    computador.pc_name,
    computador.pc_mac,
    computador.pc_so,
    computador.pc_cpu,
    computador.pc_mem,
    computador.pc_drive,
    computador.pc_serial,
    computador.admin_user,
    computador.admin_pass,
    computador.pc_malfunctions,
    computador.username,
    computador.user_pass,
    checklist.check_id,
    checklist.id_maquina,
    checklist.list_fields
   FROM ((form_values
     FULL JOIN computador ON ((computador.pedido_id = form_values.id_pedido)))
     FULL JOIN checklist ON ((checklist.id_maquina = computador.pc_id)));;